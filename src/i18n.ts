export type Key = keyof typeof EN;

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = (current === 'zh' ? ZH : EN)[key] ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// Static markup carries data-i18n="key" (text), data-i18n-aria and data-i18n-ph (placeholder).
export function translate(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) el.textContent = t(el.dataset.i18n as Key);
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria as Key));
  for (const el of root.querySelectorAll<HTMLInputElement>('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh as Key);
}

// The page's lang attribute picks the fonts (style.css) and the static text follows.
export function applyLang() {
  document.documentElement.lang = current === 'zh' ? 'zh-Hans' : 'en';
  translate();
}
