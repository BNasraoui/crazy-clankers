// Every player-visible string, in English and Simplified Chinese. t('key', { n: 3 })
// looks a string up in the current language and fills in {n}. Quips, asks and
// passenger names live with their speakers in src/lines/ and src/names.ts.

export type Lang = 'en' | 'zh';

const STORE = 'clankers.lang';
let current: Lang = (() => {
  try {
    const saved = localStorage.getItem(STORE);
    if (saved === 'en' || saved === 'zh') return saved;
  } catch { /* storage unavailable */ }
  return /^zh/i.test(navigator.language) ? 'zh' : 'en';
})();

const listeners: (() => void)[] = [];
export const lang = () => current;
export const onLang = (fn: () => void) => listeners.push(fn);

export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  try { localStorage.setItem(STORE, l); } catch { /* storage unavailable */ }
  applyLang();
  for (const fn of listeners) fn();
}

